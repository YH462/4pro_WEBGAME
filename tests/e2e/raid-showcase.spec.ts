import { test, expect } from "@playwright/test";

test("PC effects demo renders attacks with different strengths and keeps the shared raid untouched", async ({ page }, testInfo) => {
  test.setTimeout(60_000);
  const syncRequests: string[] = [];
  page.on("request", (request) => { if (request.url().includes("/api/local-raid")) syncRequests.push(request.method()); });
  await page.setViewportSize({ width: 1920, height: 1080 });
  await page.clock.install({ time: new Date("2026-10-20T06:00:00Z") });
  await page.goto("/raid/screen?demo=effects");
  const stage = page.getByRole("region", { name: "ボスとエフェクト" });
  await expect(stage).toHaveAttribute("data-renderer", "webgl", { timeout: 30_000 });
  const hp = page.getByRole("progressbar", { name: "演出デモのボスHP" });
  await expect(hp).toHaveAttribute("aria-valuenow", "450");
  await page.clock.pauseAt(new Date(await page.evaluate(() => Date.now() + 10_000)));
  await page.getByRole("button", { name: "通常攻撃", exact: true }).click();
  await page.clock.runFor(250);
  await expect(hp).toHaveAttribute("aria-valuenow", "450");
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-normal-from-hand.png") });
  await page.clock.runFor(600);
  await expect(hp).toHaveAttribute("aria-valuenow", "400");
  await expect(stage).toContainText("50");
  await page.getByRole("button", { name: "2倍攻撃", exact: true }).click();
  await page.clock.runFor(250);
  await expect(hp).toHaveAttribute("aria-valuenow", "400");
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-critical-from-hands.png") });
  await page.clock.runFor(850);
  await expect(hp).toHaveAttribute("aria-valuenow", "300");
  await expect(stage).toContainText("100");
  await page.getByRole("button", { name: "演出を一時停止", exact: true }).click();
  await expect(page.getByRole("main")).toHaveAttribute("data-paused", "true");
  await expect(stage.getByText("100", { exact: true }).locator("..")).toHaveCSS("opacity", "1");
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-critical.png") });
  await page.clock.resume();
  await page.getByRole("button", { name: "今の演出をもう一度", exact: true }).click();
  await expect(page.getByRole("main")).toHaveAttribute("data-paused", "false");
  await expect(hp).toHaveAttribute("aria-valuenow", "300");
  for (const [label, cue] of [["自己回復", "heal"], ["ボスの反撃", "counter"], ["ボス弱体", "weaken"], ["討伐成功", "victory"]]) {
    await page.getByRole("button", { name: label, exact: true }).click();
    await expect(page.getByRole("main")).toHaveAttribute("data-cue", cue);
  }
  await expect(hp).toHaveAttribute("aria-valuenow", "0");
  await expect(stage).toContainText("討伐成功");
  await page.getByRole("button", { name: "連続デモ", exact: true }).click();
  await expect(page.getByRole("button", { name: "連続デモ", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("main")).toHaveAttribute("data-cue", "idle");
  await expect(page.getByRole("main")).toHaveAttribute("data-cue", "rps", { timeout: 5000 });
  await expect(page.getByRole("main")).toHaveAttribute("data-cue", "attack", { timeout: 6000 });
  expect(syncRequests).toEqual([]);
});

test("contact freezes the rendered boss, particles and CSS before recoil and HP loss start together", async ({ page }) => {
  test.setTimeout(60_000);
  await page.clock.install();
  await page.goto("/raid/screen?demo=effects");
  const main = page.getByRole("main");
  const stage = page.getByRole("region", { name: "ボスとエフェクト" });
  await expect(stage).toHaveAttribute("data-renderer", "webgl");
  await page.clock.pauseAt(new Date(await page.evaluate(() => Date.now() + 10_000)));
  await page.getByRole("button", { name: "2倍攻撃", exact: true }).click();
  const hp = page.getByRole("progressbar", { name: "演出デモのボスHP" });
  const fill = hp.locator("span").last();
  await page.clock.runFor(620);
  await expect(main).toHaveAttribute("data-impact-phase", "flight");
  await expect(hp).toHaveAttribute("aria-valuenow", "400");
  await page.clock.runFor(50);
  await expect(main).toHaveAttribute("data-impact-phase", "hitstop");
  const stopped = await stage.locator("canvas").screenshot();
  const widthBefore = await fill.evaluate((element) => (element as HTMLElement).style.width);
  const cssTimes = () => stage.evaluate((element) => element.getAnimations({ subtree: true }).map((animation) => animation.currentTime));
  const frozenTimes = await cssTimes();
  expect(frozenTimes.length).toBeGreaterThan(0);
  await page.clock.runFor(80);
  await expect(main).toHaveAttribute("data-impact-phase", "hitstop");
  await expect(hp).toHaveAttribute("aria-valuenow", "400");
  expect(await cssTimes()).toEqual(frozenTimes);
  expect((await stage.locator("canvas").screenshot()).equals(stopped)).toBe(true);
  await page.getByRole("button", { name: "演出を一時停止", exact: true }).click();
  await page.clock.runFor(500);
  await expect(main).toHaveAttribute("data-impact-phase", "hitstop");
  await expect(hp).toHaveAttribute("aria-valuenow", "400");
  await page.getByRole("button", { name: "演出を再開", exact: true }).click();
  await page.clock.runFor(80);
  await expect(main).toHaveAttribute("data-impact-phase", "reaction");
  await expect(hp).toHaveAttribute("aria-valuenow", "300");
  const widthAfter = await fill.evaluate((element) => (element as HTMLElement).style.width);
  expect(parseFloat(widthAfter)).toBeLessThan(parseFloat(widthBefore));
  expect(parseFloat(widthAfter)).toBeGreaterThan(300 / 450 * 100);
  expect((await stage.locator("canvas").screenshot()).equals(stopped)).toBe(false);
  await page.clock.runFor(400);
  expect(parseFloat(await fill.evaluate((element) => (element as HTMLElement).style.width))).toBeCloseTo(300 / 450 * 100, 3);
});

test("boss fan breath charges, hits and pauses with the whole team's recoil, then resets on replay", async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1600, height: 900 });
  await page.clock.install();
  await page.goto("/raid/screen?demo=effects");
  const stage = page.getByRole("region", { name: "ボスとエフェクト" });
  await expect(stage).toHaveAttribute("data-renderer", "webgl");
  await page.clock.pauseAt(new Date(await page.evaluate(() => Date.now() + 10_000)));
  await page.getByRole("button", { name: "ボスの反撃", exact: true }).click();
  await page.clock.runFor(700);
  await page.getByRole("button", { name: "演出を一時停止", exact: true }).click();
  await page.clock.runFor(40);
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-counter-charge.png") });
  const charge = await stage.locator("canvas").screenshot();
  await page.getByRole("button", { name: "演出を再開", exact: true }).click();
  await page.clock.runFor(790);
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-counter-breath.png") });
  await page.clock.runFor(230);
  await page.getByRole("button", { name: "演出を一時停止", exact: true }).click();
  // Flush the frame at the exact pause timestamp (between two render ticks).
  await page.clock.runFor(40);
  const impact = await stage.locator("canvas").screenshot();
  expect(impact.equals(charge)).toBe(false);
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-counter-impact.png") });
  const animationTimes = () => stage.evaluate((element) => element.getAnimations({ subtree: true }).map((animation) => animation.currentTime));
  const frozenTimes = await animationTimes();
  await page.clock.runFor(500);
  expect((await stage.locator("canvas").screenshot()).equals(impact)).toBe(true);
  expect(await animationTimes()).toEqual(frozenTimes);
  await expect(page.getByRole("progressbar", { name: "演出デモのボスHP" })).toHaveAttribute("aria-valuenow", "300");
  await page.getByRole("button", { name: "演出を再開", exact: true }).click();
  await page.clock.runFor(1700);
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-counter-recovered.png") });
  expect((await stage.locator("canvas").screenshot()).equals(impact)).toBe(false);
  await page.getByRole("button", { name: "今の演出をもう一度", exact: true }).click();
  await page.clock.runFor(700);
  await page.getByRole("button", { name: "演出を一時停止", exact: true }).click();
  await page.clock.runFor(40);
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-counter-replay.png") });
  const replayTimes = await animationTimes();
  expect(replayTimes.length).toBe(frozenTimes.length);
  for (const time of replayTimes) expect(Number(time)).toBeCloseTo(700, -1);
  expect((await stage.locator("canvas").screenshot()).equals(impact)).toBe(false);
});

test("model-independent boss RPS symbols reveal the selected hand and pause on the shared timeline", async ({ page }, testInfo) => {
  test.setTimeout(90_000);
  await page.setViewportSize({ width: 1600, height: 900 });
  await page.clock.install();
  await page.goto("/raid/screen?demo=effects");
  const stage = page.getByRole("region", { name: "ボスとエフェクト" });
  await expect(stage).toHaveAttribute("data-renderer", "webgl");
  await page.clock.pauseAt(new Date(await page.evaluate(() => Date.now() + 10_000)));
  await page.getByRole("button", { name: "ボスのじゃんけん", exact: true }).click();
  await page.clock.runFor(900);
  await expect(stage.getByRole("status")).toHaveText("ボスがじゃんけんをしています");
  await page.getByRole("button", { name: "演出を一時停止", exact: true }).click();
  await page.clock.runFor(40);
  const paused = await stage.locator("canvas").screenshot();
  const animations = () => stage.evaluate((element) => element.getAnimations({ subtree: true }).map((animation) => animation.currentTime));
  const pausedTimes = await animations();
  expect(pausedTimes.length).toBeGreaterThan(0);
  const symbol = stage.locator("[data-rps-hand]");
  const pausedHand = await symbol.getAttribute("data-rps-hand");
  await page.clock.runFor(1800);
  expect((await stage.locator("canvas").screenshot()).equals(paused)).toBe(true);
  expect(await animations()).toEqual(pausedTimes);
  await expect(symbol).toHaveAttribute("data-rps-hand", pausedHand!);
  await expect(stage.getByRole("status")).toHaveText("ボスがじゃんけんをしています");
  await page.getByRole("button", { name: "演出を再開", exact: true }).click();
  await page.clock.runFor(1500);
  await expect(stage.getByRole("status")).toHaveText("ボスの手はパーです");
  await expect(symbol).toHaveAttribute("data-rps-hand", "paper");
  await expect(symbol).toHaveAttribute("data-revealed", "true");
  await page.screenshot({ path: testInfo.outputPath("raid-showcase-boss-rps-paper.png") });
  for (const [label, hand] of [["グー", "rock"], ["チョキ", "scissors"]]) {
    await page.getByRole("button", { name: `${label}で再生`, exact: true }).click();
    await expect(stage.getByRole("status")).toHaveText("ボスがじゃんけんをしています");
    await page.clock.runFor(2450);
    await expect(stage.getByRole("status")).toHaveText(`ボスの手は${label}です`);
    await expect(symbol).toHaveAttribute("data-rps-hand", hand);
    await page.screenshot({ path: testInfo.outputPath(`raid-showcase-boss-rps-${hand}.png`) });
  }
  await expect(page.getByRole("progressbar", { name: "演出デモのボスHP" })).toHaveAttribute("aria-valuenow", "450");
  await page.getByRole("button", { name: "通常攻撃", exact: true }).click();
  await expect(stage.getByRole("status")).toHaveCount(0);
  await expect(page.getByRole("group", { name: "デモのボスの手" })).toHaveCount(0);
});

test("the visual demo remains controllable without WebGL and with reduced motion", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.addInitScript(() => {
    const original = HTMLCanvasElement.prototype.getContext;
    Object.defineProperty(HTMLCanvasElement.prototype, "getContext", { value: function (this: HTMLCanvasElement, type: string, ...args: unknown[]) {
      if (["webgl", "webgl2", "experimental-webgl"].includes(type)) return null;
      return Reflect.apply(original, this, [type, ...args]);
    } });
  });
  await page.goto("/raid/screen?demo=effects");
  await expect(page.getByRole("region", { name: "ボスとエフェクト" })).toHaveAttribute("data-renderer", "fallback");
  await expect(page.locator(".enemy-fallback-art")).toBeVisible();
  await expect(page.getByRole("button", { name: "連続デモ", exact: true })).toHaveAttribute("aria-pressed", "false");
  await page.getByRole("button", { name: "自己回復", exact: true }).click();
  await expect(page.getByRole("region", { name: "ボスとエフェクト" })).toContainText("+60");
  await page.getByRole("button", { name: "ボスのじゃんけん", exact: true }).click();
  await expect(page.getByRole("region", { name: "ボスとエフェクト" }).getByRole("status").filter({ hasText: "ボスの手はパーです" })).toBeVisible();
  await expect(page.locator('[data-rps-hand="paper"][data-revealed="true"]')).toBeVisible();
  await expect(page.getByRole("region", { name: "レイド参加案内" }).getByRole("button", { name: "参加QRを大きく表示" })).toBeVisible();
});
